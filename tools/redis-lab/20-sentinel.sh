#!/usr/bin/env bash
# Sentinel：rs1（主）、rs2、rs3（從），三台都跑 Sentinel。照文章步驟操作並做切換測試
source "$(dirname "$0")/lib.sh"
N="rs1 rs2 rs3"
docker compose rm -sf $N >/dev/null 2>&1; docker compose up -d $N; sleep 5
ip() { case $1 in rs1) echo 192.168.58.21;; rs2) echo 192.168.58.22;; rs3) echo 192.168.58.23;; esac; }
# 等到條件成立（最多 max 秒），印出等了幾秒；取代固定 sleep
wait_until() {
  local n=$1 cond=$2 max=${3:-60} t0=$(date +%s)
  for i in $(seq 1 $max); do
    if docker compose exec -T $n bash -c "export REDISCLI_AUTH=ChangeMe_Redis_2026; $cond" >/dev/null 2>&1; then
      echo "$(date '+%T') [$n] 條件成立：$cond（等了 $(( $(date +%s)-t0 )) 秒）"; return 0
    fi
    sleep 1
  done
  echo "$(date '+%T') [$n] 逾時 ${max} 秒：$cond"; return 1
}
# 問任一台還有回應的 Sentinel（被 pause 的節點 exec 會失敗，換下一台）
master() { local n m; for n in $N; do m=$(docker compose exec -T $n redis-cli -p 26379 sentinel get-master-addr-by-name mymaster 2>/dev/null | head -1); [ -n "$m" ] && { echo "$m"; return; }; done; }
{
note "環境"
x rs1 'cat /etc/rocky-release; redis-server --version'

note "步驟 0~2：OS 參數、使用者與目錄（三台都做）"
for n in $N; do
  x $n 'mkdir -p /etc/sysctl.d && cp /root/conf/99-redis.conf /etc/sysctl.d/ && sysctl -p /etc/sysctl.d/99-redis.conf >/dev/null && groupadd -r redis && useradd -r -g redis -s /sbin/nologin -d /var/lib/redis redis && mkdir -p /etc/redis /var/lib/redis /var/lib/redis-sentinel /var/log/redis && chown -R redis:redis /etc/redis /var/lib/redis /var/lib/redis-sentinel /var/log/redis && chmod 750 /etc/redis /var/lib/redis /var/lib/redis-sentinel /var/log/redis && echo ok'
done

note "步驟 3：redis.conf（三台），rs2 / rs3 加上 replicaof"
for n in $N; do
  x $n "install -o redis -g redis -m 640 /root/conf/redis-sentinel.conf /etc/redis/redis.conf && sed -i 's/^bind 192.168.58.21 /bind $(ip $n) /' /etc/redis/redis.conf && grep '^bind' /etc/redis/redis.conf"
done
for n in rs2 rs3; do
  x $n "echo 'replicaof 192.168.58.21 6379' >> /etc/redis/redis.conf && tail -1 /etc/redis/redis.conf"
done

note "步驟 4：啟動 Redis（先主後從）"
for n in $N; do
  x $n 'cp /root/conf/redis.service /etc/systemd/system/ && systemctl daemon-reload && systemctl enable --now redis && systemctl is-active redis'
done
sleep 3
x rs1 'redis-cli info replication'
x rs2 'redis-cli info replication | head -12'
x rs1 'grep -E "Replica .* asks|Synchronization with replica|Starting BGSAVE|diskless|succeeded" /var/log/redis/redis.log'
x rs2 'grep -E "MASTER <-> REPLICA|Connecting to MASTER|Loading|Finished|Successful" /var/log/redis/redis.log'
cmpconf rs1 /etc/redis/redis.conf

note "步驟 5：sentinel.conf 與啟動 Sentinel（三台）"
for n in $N; do
  x $n "install -o redis -g redis -m 640 /root/conf/sentinel.conf /etc/redis/sentinel.conf && sed -i 's/^bind 192.168.58.21 /bind $(ip $n) /' /etc/redis/sentinel.conf && cp /root/conf/redis-sentinel.service /etc/systemd/system/ && systemctl daemon-reload && systemctl enable --now redis-sentinel && systemctl is-active redis-sentinel"
done
sleep 12
x rs1 'cat /var/log/redis/sentinel.log'
x rs1 'redis-cli -p 26379 sentinel get-master-addr-by-name mymaster'
x rs1 'redis-cli -p 26379 sentinel master mymaster | paste - - | grep -E "^(name|ip|port|flags|num-slaves|num-other-sentinels|quorum|down-after-milliseconds|failover-timeout|parallel-syncs)\s"'
x rs1 'redis-cli -p 26379 sentinel replicas mymaster | paste - - | grep -E "^(name|flags|master-link-status|slave-priority)\s"'
x rs1 'redis-cli -p 26379 sentinel ckquorum mymaster'
x rs1 'redis-cli -p 26379 info sentinel'
x rs1 'tail -12 /etc/redis/sentinel.conf'

note "Sentinel 預設值（另起一個只設 monitor 的 Sentinel 查詢）"
x rs1 'printf "port 26399\nsentinel monitor m 127.0.0.1 6379 1\n" > /tmp/s.conf; redis-sentinel /tmp/s.conf --daemonize yes --logfile /tmp/s.log; sleep 1; redis-cli -p 26399 sentinel config get "*" | paste - -; redis-cli -p 26399 sentinel master m | paste - - | grep -E "^(down-after-milliseconds|failover-timeout|parallel-syncs|quorum)\s"; redis-cli -p 26399 shutdown nosave'

note "資料寫入與讀取"
x rs1 'redis-cli set order:1 "keyboard" && redis-cli incr counter:orders'
x rs3 'redis-cli get order:1; redis-cli set should:fail 1'

note "測試 1：計畫內切換 SENTINEL FAILOVER"
x rs1 'redis-cli -p 26379 sentinel failover mymaster'
wait_until rs1 'redis-cli info replication | grep -q "^master_link_status:up"' 60
x rs1 'redis-cli -p 26379 sentinel get-master-addr-by-name mymaster'
x rs1 'grep -E "\+(try-failover|elected-leader|selected-slave|promoted-slave|switch-master|failover-end|convert-to-slave)" /var/log/redis/sentinel.log | tail -8'
x rs1 'redis-cli info replication | head -5'
x rs1 'grep -n -A3 "Generated by CONFIG REWRITE" /etc/redis/redis.conf'
NEWM=$(master); echo "目前主庫：$NEWM"

note "測試 2：主庫無回應（docker pause 模擬當機 / 網路中斷）"
MN=$(for n in $N; do [ "$(ip $n)" = "$NEWM" ] && echo $n; done)
OBS=$(for n in $N; do [ "$n" != "$MN" ] && echo $n; done | head -1)
x $MN 'redis-cli set before:crash 1'
T0=$(date +%s); echo "$(date '+%T') docker compose pause $MN"; docker compose pause $MN
for i in $(seq 1 60); do
  m=$(docker compose exec -T $OBS redis-cli -p 26379 sentinel get-master-addr-by-name mymaster | head -1)
  if [ "$m" != "$NEWM" ]; then echo "$(date '+%T') 新主庫 $m，經過 $(( $(date +%s)-T0 )) 秒"; break; fi
  sleep 1
done
x $OBS 'grep -E "\+(sdown|odown|try-failover|elected-leader|selected-slave|promoted-slave|switch-master|failover-end)" /var/log/redis/sentinel.log | tail -9'
NM=$(master); NMN=$(for n in $N; do [ "$(ip $n)" = "$NM" ] && echo $n; done)
x $NMN 'redis-cli get before:crash; redis-cli set after:crash 1; redis-cli info replication | head -4'
wait_until $NMN 'redis-cli info replication | grep -q "^min_slaves_good_slaves:[1-9]"' 60
x $NMN 'redis-cli set after:crash 1; redis-cli info replication | head -4'
note "舊主庫恢復"
echo "$(date '+%T') docker compose unpause $MN"; docker compose unpause $MN
wait_until $MN 'redis-cli info replication | grep -q "^master_link_status:up"' 60
x $MN 'redis-cli info replication | head -6; redis-cli get after:crash'
x $OBS 'grep -E "convert-to-slave|\-sdown" /var/log/redis/sentinel.log | tail -3'

note "測試 3：min-replicas-to-write——兩台從庫都停掉時主庫拒絕寫入"
NM=$(master); NMN=$(for n in $N; do [ "$(ip $n)" = "$NM" ] && echo $n; done)
for n in $N; do [ "$n" != "$NMN" ] && x $n 'systemctl stop redis'; done
sleep 12
x $NMN 'redis-cli info replication | grep -E "connected_slaves|min_slaves_good_slaves"; redis-cli set x 1'
for n in $N; do [ "$n" != "$NMN" ] && x $n 'systemctl start redis'; done
sleep 8
x $NMN 'redis-cli info replication | grep -E "connected_slaves|min_slaves_good_slaves"; redis-cli set x 1'
note "最後狀態"
x rs1 'redis-cli -p 26379 sentinel master mymaster | paste - - | grep -E "^(ip|flags|num-slaves|num-other-sentinels)\s"'
for n in $N; do x $n 'grep -E "WARNING" /var/log/redis/redis.log /var/log/redis/sentinel.log || echo "(no warnings)"'; done
} 2>&1 | tee results/20-sentinel.log
